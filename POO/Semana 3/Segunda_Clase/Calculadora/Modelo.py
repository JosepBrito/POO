class CalculadoraModelo:

    def sumar(self, a, b):
        return a + b

    def restar(self, a,b):
        return a - b
    
    def multiplicar(self, a, b):
        return a * b

    def dividir (self, a, b):
        return a / b

    def residuo(self, a, b):
        return a % b

    def potencia(self, base, exponente):
        return base ** exponente